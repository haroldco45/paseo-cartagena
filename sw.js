const CACHE = 'paseo-cartagena-v1';
const CORE = ['./','./index.html','./manifest.json','./icon.svg','./volante.jpg',
  './foto-baru.jpg','./foto-lancha.jpg','./foto-chiva.jpg','./foto-noche-blanco.jpg','./foto-bocagrande.jpg'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE))); self.skipWaiting(); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))));
  self.clients.claim();
});
// Red primero: si cambian precio o fechas, se ve al instante
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith(fetch(e.request).then(r => { const c = r.clone(); caches.open(CACHE).then(x => x.put(e.request, c)); return r; })
    .catch(() => caches.match(e.request).then(r => r || caches.match('./index.html'))));
});
